export function isMetaIconKey(value?: string | null): value is MetaIconKey {
  return !!value && value in META_ICON_MAP
}

export function resolveMetaIcon(icon?: string | null, name?: string | null): MetaIconKey {
  if (isMetaIconKey(icon)) return icon
  if (name) {
    for (const hint of NAME_HINTS) {
      if (hint.match.test(name)) return hint.icon
    }
  }
  return 'Tag'
}

/** 账户：优先已存 icon → 名称猜测 → 类型默认 → Wallet */
export function resolveAccountIcon(
  icon?: string | null,
  name?: string | null,
  type?: string | null,
): MetaIconKey {
  if (isMetaIconKey(icon)) return icon
  if (name) {
    for (const hint of NAME_HINTS) {
      if (hint.match.test(name)) return hint.icon
    }
  }
  if (type && ACCOUNT_TYPE_ICONS[type]) return ACCOUNT_TYPE_ICONS[type]
  return 'Wallet'
}

export function getMetaIconComponent(icon?: string | null, name?: string | null): Component {
  return META_ICON_MAP[resolveMetaIcon(icon, name)]
}

export function getAccountIconComponent(
  icon?: string | null,
  name?: string | null,
  type?: string | null,
): Component {
  return META_ICON_MAP[resolveAccountIcon(icon, name, type)]
}
